// Connects the app to the Google Form: reads the form's field IDs and writes data/formConfig.ts.
// Run after creating the form: npm run form:sync -- <form link>

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { formItems } from '../data/formSpec';

async function main() {
  const link = process.argv[2];
  if (!link) throw new Error('Usage: npm run form:sync -- <form link from the Apps Script log>');

  const res = await fetch(link, { redirect: 'follow' });
  if (!res.ok) throw new Error(`Couldn't open the form (${res.status}). Is it published and accepting responses?`);
  const html = await res.text();
  const match = html.match(/FB_PUBLIC_LOAD_DATA_ = (.*?);<\/script>/s);
  if (!match) throw new Error("That link doesn't look like a published Google Form (it may require sign-in).");

  const data = JSON.parse(match[1]);
  const fields: unknown[][] = data[1][1];
  const pages = fields.filter((f) => f[3] === 8).length + 1;
  const entryByTitle = new Map<string, number>();
  for (const f of fields) {
    const inputs = f[4] as unknown[][] | null;
    if (inputs?.[0]) entryByTitle.set(String(f[1]).trim(), inputs[0][0] as number);
  }

  const entries: Record<string, number> = {};
  const missing: string[] = [];
  for (const item of formItems()) {
    if (item.type === 'page') continue;
    const id = entryByTitle.get(item.title.trim());
    if (id === undefined) missing.push(item.title);
    else entries[item.key] = id;
  }
  if (missing.length) {
    throw new Error(`These questions aren't in the form (re-run the Apps Script after quiz changes):\n- ${missing.join('\n- ')}`);
  }

  const responseUrl = res.url.replace(/\/viewform.*$/, '/formResponse');
  const config = { responseUrl, viewUrl: res.url.split('?')[0], pageHistory: Array.from({ length: pages }, (_, i) => i).join(','), entries };
  const out = join(__dirname, '..', 'data', 'formConfig.ts');
  writeFileSync(
    out,
    `// Generated by \`npm run form:sync\`. Connects the app to its Google Form.\n\nimport type { FormConfig } from './formSubmit';\n\nexport const FORM_CONFIG: FormConfig | null = ${JSON.stringify(config, null, 2)};\n`,
  );
  console.log(`Connected ${Object.keys(entries).length} questions across ${pages} pages → ${out}`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
